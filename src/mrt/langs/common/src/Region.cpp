CRegion::CRegion(const wchar_t* const region)
{
    m_regionId = TryFindRegionId(region);
    m_tableIndex = m_regionId < LastRegionTableIndex ? m_regionId : LastRegionTableIndex;

    while ((m_tableIndex != 0) && (regionsTable[m_tableIndex].regionId > m_regionId))
    {
        --m_tableIndex;
    }

    while ((m_tableIndex < LastRegionTableIndex) && (regionsTable[m_tableIndex].regionId < m_regionId))
    {
        ++m_tableIndex;
    }
}

std::uint32_t CRegion::TryFindRegionId(const wchar_t* const region)
{
    std::uint32_t result = 0;
    int regionCode = _wtoi(region);
    if (regionCode > 0)
    {
        for (std::uint32_t index = 0; index < 281; ++index)
        {
            if (regionsTable[index].regionCode == regionCode)
            {
                return regionsTable[index].regionId;
            }
        }
    }
    else
    {
        std::uint64_t searchKey;
        if (InitSearchKey(region, 3, &searchKey) && TryFindTableEntry(searchKey, 0, SearchTableRegions, &searchKey, nullptr))
        {
            result = static_cast<std::uint16_t>(searchKey);
        }
    }

    return result;
}

HRESULT CRegion::Compare(const CRegion& other, double* const score) const
{
    if ((score == nullptr) || (m_regionId == 0) || (other.m_regionId == 0))
    {
        return E_INVALIDARG;
    }

    if (m_regionId == other.m_regionId)
    {
        *score = 1.0;
    }
    else
    {
        std::uint32_t otherRegionCode = regionsTable[other.m_tableIndex].regionCode;
        std::uint32_t compositeRegionCode = regionsTable[m_tableIndex].compositeRegionCode;
        double currentScore = 0.75;
        *score = currentScore;

        do
        {
            if (otherRegionCode == compositeRegionCode)
            {
                break;
            }

            currentScore -= 0.25;
            *score = currentScore;
            compositeRegionCode = GetCompositeRegionCode(compositeRegionCode);
        } while (currentScore != 0.0);
    }

    return S_OK;
}

std::uint32_t CRegion::GetCompositeRegionCode(const std::uint32_t regionCode)
{
    if (regionCode <= 1)
    {
        return 0;
    }

    for (std::uint32_t index = LastRegionTableIndex; index != 0; --index)
    {
        if (regionsTable[index].regionCode == regionCode)
        {
            return regionsTable[index].compositeRegionCode;
        }
    }

    return 1;
}

